/**
 * Compiles dist/runyard. The built dashboard is embedded with `type: "file"`
 * imports from a generated entry, so the binary needs nothing beside it.
 */
import { $, Glob } from "bun";
import { mkdir, rm } from "node:fs/promises";
import { join, relative, resolve } from "node:path";

const root = resolve(import.meta.dir, "..");
const dashboardDist = resolve(root, "../dashboard/dist");
const genDir = join(root, ".gen");
const entry = join(genDir, "entry.ts");

if (!(await Bun.file(join(dashboardDist, "index.html")).exists())) {
  console.error(
    `No dashboard build at ${dashboardDist}. Run \`vp run -r build\` from the repository root.`,
  );
  process.exit(1);
}

const files = [...new Glob("**/*").scanSync({ cwd: dashboardDist, onlyFiles: true })].sort();
const imports = files.map((f, i) => {
  const spec = relative(genDir, join(dashboardDist, f)).split("\\").join("/");
  return `import a${i} from ${JSON.stringify(spec)} with { type: "file" };`;
});
const entries = files.map((f, i) => `  [${JSON.stringify(`/${f.split("\\").join("/")}`)}, a${i}],`);

await rm(genDir, { recursive: true, force: true });
await mkdir(genDir, { recursive: true });
await Bun.write(
  entry,
  [
    "// Generated by scripts/build.ts.",
    'import { start } from "@runyard/server/server";',
    ...imports,
    "",
    "start(new Map<string, string>([",
    ...entries,
    "]));",
    "",
  ].join("\n"),
);

await $`bun build --compile --minify --sourcemap ${entry} --outfile ${join(root, "dist", "runyard")}`.cwd(
  root,
);
console.log(`Embedded ${files.length} dashboard files.`);
