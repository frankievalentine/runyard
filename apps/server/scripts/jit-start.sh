#!/usr/bin/env bash
# Starts one one-job runner from an on-demand pool's template: copies the
# template into its own directory under <pool>/jobs/, starts the runner
# detached from this SSH session, and deletes the directory when it exits.
# The single-use registration arrives on SSH stdin and is passed to the runner
# in its environment or its own config file, never on a command line.
set -euo pipefail

: "${RF_TEMPLATE:?}"
: "${RF_JOB_DIR:?}"
: "${RF_NAME:?}"
: "${RF_KIND:?}"

pool_dir="${RF_TEMPLATE%/*}"
case "$RF_TEMPLATE" in
  "$HOME/runyard-runners"/*/template-actions | "$HOME/runyard-runners"/*/template-forgejo) ;;
  *) echo "refusing template outside $HOME/runyard-runners: $RF_TEMPLATE" >&2; exit 2 ;;
esac
case "$RF_JOB_DIR" in
  "$pool_dir"/jobs/*) ;;
  *) echo "refusing job directory outside $pool_dir/jobs: $RF_JOB_DIR" >&2; exit 2 ;;
esac
test -f "$RF_TEMPLATE/.runyard-template" || { echo "no template at $RF_TEMPLATE; review the machine's changes first" >&2; exit 3; }
test ! -e "$RF_JOB_DIR" || { echo "refusing to reuse $RF_JOB_DIR" >&2; exit 3; }

mkdir -p "$pool_dir/jobs"
# A copy-on-write clone where the filesystem has one; a plain copy otherwise.
if [ "$(uname -s)" = Darwin ]; then
  cp -cR "$RF_TEMPLATE" "$RF_JOB_DIR" 2>/dev/null || cp -R "$RF_TEMPLATE" "$RF_JOB_DIR"
else
  cp -R --reflink=auto "$RF_TEMPLATE" "$RF_JOB_DIR" 2>/dev/null || cp -R "$RF_TEMPLATE" "$RF_JOB_DIR"
fi
rm -f "$RF_JOB_DIR/.runyard-template"
cd "$RF_JOB_DIR"
umask 077
# Its jobs are recorded for run history, like a persistent runner's.
if [ "$RF_KIND" = actions ]; then runyard_job_hooks "$(pwd -P)" "$RF_NAME"; fi

if [ "$RF_KIND" = actions ]; then
  : "${RF_JIT_CONFIG:?}"
  printf '%s' "$RF_JIT_CONFIG" > .jitconfig
  unset RF_JIT_CONFIG
  # The runner reads command-line inputs from ACTIONS_RUNNER_INPUT_* variables.
  run='ACTIONS_RUNNER_INPUT_JITCONFIG="$(cat .jitconfig)"; rm -f .jitconfig; export ACTIONS_RUNNER_INPUT_JITCONFIG; ./run.sh'
else
  : "${RF_URL:?}" "${RF_RUNNER_ID:?}" "${RF_UUID:?}" "${RF_TOKEN:?}" "${RF_LABELS:?}"
  labels_json="$(printf '%s' "$RF_LABELS" | awk -F, '{for(i=1;i<=NF;i++) printf "%s\"%s\"", (i>1?", ":""), $i}')"
  cat > .runner <<RUNNER
{
  "WARNING": "Generated by Runyard for one job.",
  "id": $RF_RUNNER_ID,
  "uuid": "$RF_UUID",
  "name": "$RF_NAME",
  "token": "$RF_TOKEN",
  "address": "$RF_URL",
  "labels": [$labels_json]
}
RUNNER
  unset RF_TOKEN
  ./forgejo-runner generate-config > config.yml
  run='./forgejo-runner one-job --config config.yml'
fi

# setsid, where there is one, keeps the runner out of this session's process group.
# When the runner exits, its directory goes, but its log is kept first in jobs/.logs (the
# last 20, at most 7 days): the runner's output, then the end of its own diagnostic logs,
# where the reason a job was lost is written.
logs="$pool_dir/jobs/.logs"
mkdir -p "$logs"
keep_log="status=\$?; echo; echo \"Runyard: the runner exited with status \$status at \$(date -u +%Y-%m-%dT%H:%M:%SZ).\"; { cat runner.log; for f in \$(ls -t _diag/Runner_*.log _diag/Worker_*.log 2>/dev/null | head -n 4); do echo; echo \"== \$f (last 150 lines) ==\"; tail -n 150 \"\$f\"; done; } > '$logs/$RF_NAME.log' 2>/dev/null; ls -1t '$logs'/*.log 2>/dev/null | tail -n +21 | xargs rm -f 2>/dev/null; find '$logs' -name '*.log' -mtime +7 -exec rm -f {} + 2>/dev/null"

launcher=()
if command -v setsid >/dev/null 2>&1; then launcher=(setsid); fi
${launcher[@]+"${launcher[@]}"} nohup bash -c "cd '$RF_JOB_DIR' && $run; $keep_log; cd / && rm -rf '$RF_JOB_DIR'; exit \$status" \
  > "$RF_JOB_DIR/runner.log" 2>&1 < /dev/null &
echo $! > "$RF_JOB_DIR/.pid"
echo "started $RF_NAME (pid $!) in $RF_JOB_DIR"
