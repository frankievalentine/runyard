#!/usr/bin/env bash
# Installs one forgejo-runner on a Linux machine as a systemd service running as
# this user. Runyard supplies RF_* values on SSH stdin, ahead of run_as_root.
# The runner's Forgejo credentials go only into its own .runner file (mode 600).
set -euo pipefail

: "${RF_ROOT:?}"
: "${RF_NAME:?}"
: "${RF_URL:?}"
: "${RF_RUNNER_ID:?}"
: "${RF_UUID:?}"
: "${RF_TOKEN:?}"
: "${RF_LABELS:?}"
: "${RF_BINARY_URL:?}"
: "${RF_BINARY_NAME:?}"
: "${RF_CHECKSUM:?}"
: "${RF_MODE:?}"

case "$RF_BINARY_URL" in
  https://code.forgejo.org/forgejo/runner/releases/download/*) ;;
  *) echo "refusing unexpected forgejo-runner download URL: $RF_BINARY_URL" >&2; exit 2 ;;
esac
case "$RF_ROOT" in
  "$HOME/runyard-runners"/*) ;;
  *) echo "refusing root outside $HOME/runyard-runners: $RF_ROOT" >&2; exit 2 ;;
esac
[ "$(uname -s)" = Linux ] || { echo "forgejo-runner is only published for Linux" >&2; exit 2; }
command -v systemctl >/dev/null 2>&1 || { echo "systemd is required to run forgejo-runner as a service" >&2; exit 2; }
if [ "$RF_MODE" = docker ] && ! docker info >/dev/null 2>&1; then
  echo "Docker mode needs Docker installed and usable by $(id -un) (for example, in the docker group)" >&2
  exit 2
fi

# Named after its directory, which is unique on the machine: a pool serving several Forgejo
# scopes has a runner of the same name in each. Runners installed before keep theirs (.service).
unit="runyard-forgejo-$(printf '%s' "${RF_ROOT#"$HOME/runyard-runners/"}" | tr -c 'A-Za-z0-9_.-' '-').service"


if [ -f "$RF_ROOT/.runner" ]; then
  if ! tr -d '[:space:]' < "$RF_ROOT/.runner" | grep -F "\"name\":\"$RF_NAME\"" >/dev/null; then
    echo "configured runner at exact path does not have expected name $RF_NAME" >&2
    exit 3
  fi
  run_as_root systemctl start "$(cat "$RF_ROOT/.service")"
  echo "runner $RF_NAME already configured; ensured its service is started"
  exit 0
fi
if [ -d "$RF_ROOT" ] && [ -n "$(find "$RF_ROOT" -mindepth 1 -maxdepth 1 -print -quit)" ]; then
  echo "refusing non-empty unconfigured directory: $RF_ROOT" >&2
  exit 3
fi

mkdir -p "$RF_ROOT"
binary="$(mktemp "${TMPDIR:-/tmp}/runyard.XXXXXX")"
cleanup() { rm -f "$binary"; }
trap cleanup EXIT HUP INT TERM
echo "downloading $RF_BINARY_NAME"
curl --fail --location --silent --show-error "$RF_BINARY_URL" --output "$binary"
actual="$(sha256sum "$binary" | awk '{print $1}')"
if [ "$actual" != "$RF_CHECKSUM" ]; then
  echo "SHA-256 mismatch for $RF_BINARY_NAME" >&2
  exit 4
fi
echo "verified the published SHA-256"
install -m 755 "$binary" "$RF_ROOT/forgejo-runner"

cd "$RF_ROOT"
labels_json="$(printf '%s' "$RF_LABELS" | awk -F, '{for(i=1;i<=NF;i++) printf "%s\"%s\"", (i>1?", ":""), $i}')"
umask 077
cat > .runner <<RUNNER
{
  "WARNING": "Generated by Runyard. Holds this runner's Forgejo credentials.",
  "id": $RF_RUNNER_ID,
  "uuid": "$RF_UUID",
  "name": "$RF_NAME",
  "token": "$RF_TOKEN",
  "address": "$RF_URL",
  "labels": [$labels_json]
}
RUNNER
unset RF_TOKEN
umask 022
./forgejo-runner generate-config > config.yml

# Written as this user, then installed by root: run_as_root may feed the sudo
# password on stdin, so it can't also carry the unit file.
unit_file="$(mktemp "${TMPDIR:-/tmp}/runyard-unit.XXXXXX")"
cat > "$unit_file" <<UNIT
[Unit]
Description=Forgejo runner $RF_NAME (Runyard)
After=network-online.target
Wants=network-online.target

[Service]
User=$(id -un)
WorkingDirectory=$RF_ROOT
ExecStart=$RF_ROOT/forgejo-runner daemon --config $RF_ROOT/config.yml
# Run history reads which tasks it took from here; the account can read it without sudo.
StandardOutput=append:$RF_ROOT/runner.log
StandardError=append:$RF_ROOT/runner.log
Restart=on-failure
RestartSec=10

[Install]
WantedBy=multi-user.target
UNIT
run_as_root install -m 644 "$unit_file" "/etc/systemd/system/$unit"
rm -f "$unit_file"
printf '%s\n' "$unit" > .service
printf '1\n' > .runyard-history

run_as_root systemctl daemon-reload
run_as_root systemctl enable --now "$unit"
unset RF_SUDO_PASSWORD
echo "installed and started $RF_NAME at $RF_ROOT"
